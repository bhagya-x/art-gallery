<?php
require_once __DIR__ . '/../includes/helpers.php';
require_once __DIR__ . '/../config/database.php';
require_admin();

$inventory = $pdo->query("SELECT category, status, COUNT(*) AS total, COALESCE(SUM(price),0) AS value FROM artworks GROUP BY category, status ORDER BY category")->fetchAll();
$sales = $pdo->query("SELECT DATE(created_at) AS order_date, COUNT(*) AS orders_count, COALESCE(SUM(total),0) AS total_value FROM orders GROUP BY DATE(created_at) ORDER BY order_date DESC LIMIT 30")->fetchAll();
$topCustomers = $pdo->query("SELECT users.name, users.email, COUNT(orders.id) AS orders_count, COALESCE(SUM(orders.total),0) AS total_value FROM users JOIN orders ON users.id = orders.user_id GROUP BY users.id ORDER BY total_value DESC LIMIT 10")->fetchAll();
$summary = [
    'artworks' => (int)$pdo->query("SELECT COUNT(*) FROM artworks")->fetchColumn(),
    'orders' => (int)$pdo->query("SELECT COUNT(*) FROM orders")->fetchColumn(),
    'customers' => (int)$pdo->query("SELECT COUNT(*) FROM users WHERE role='customer'")->fetchColumn(),
    'revenue' => (float)$pdo->query("SELECT COALESCE(SUM(total),0) FROM orders")->fetchColumn(),
];
$orderStatuses = $pdo->query("SELECT status, COUNT(*) AS total, COALESCE(SUM(total),0) AS value FROM orders GROUP BY status ORDER BY status")->fetchAll();

class PremiumPdf
{
    private array $pages = [];
    private string $content = '';
    private float $y = 0;
    private int $pageNo = 0;
    private const W = 595.28;
    private const H = 841.89;

    public function __construct()
    {
        $this->addPage();
    }

    private function clean(string $text): string
    {
        $text = html_entity_decode(strip_tags($text), ENT_QUOTES, 'UTF-8');
        $text = preg_replace('/[^\x20-\x7E]/', ' ', $text) ?? '';
        return trim(preg_replace('/\s+/', ' ', $text) ?? '');
    }

    private function esc(string $text): string
    {
        return str_replace(['\\', '(', ')'], ['\\\\', '\\(', '\\)'], $this->clean($text));
    }

    public function addPage(): void
    {
        if ($this->content !== '') {
            $this->footer();
            $this->pages[] = $this->content;
        }
        $this->pageNo++;
        $this->content = '';
        $this->y = 780;
        $this->rect(0, 0, self::W, self::H, [1, 1, 1]);
        $this->rect(0, 806, self::W, 36, [0.04, 0.04, 0.04]);
        $this->text(42, 818, APP_NAME . ' | Professional Report', 9, true, [1, 1, 1]);
        $this->text(462, 818, date('Y-m-d H:i'), 9, false, [1, 1, 1]);
    }

    private function footer(): void
    {
        $this->line(42, 46, 553, 46, [0.86, 0.86, 0.86]);
        $this->text(42, 28, 'Generated by Arts Gallery Admin Panel', 8, false, [0.38, 0.38, 0.38]);
        $this->text(520, 28, 'Page ' . $this->pageNo, 8, false, [0.38, 0.38, 0.38]);
    }

    private function ensure(float $height): void
    {
        if ($this->y - $height < 72) {
            $this->addPage();
        }
    }

    public function text(float $x, float $y, string $text, int $size = 10, bool $bold = false, array $rgb = [0,0,0]): void
    {
        $font = $bold ? 'F2' : 'F1';
        $this->content .= sprintf("q %.3F %.3F %.3F rg BT /%s %d Tf 1 0 0 1 %.2F %.2F Tm (%s) Tj ET Q\n", $rgb[0], $rgb[1], $rgb[2], $font, $size, $x, $y, $this->esc($text));
    }

    public function rect(float $x, float $y, float $w, float $h, array $rgb): void
    {
        $this->content .= sprintf("q %.3F %.3F %.3F rg %.2F %.2F %.2F %.2F re f Q\n", $rgb[0], $rgb[1], $rgb[2], $x, $y, $w, $h);
    }

    public function line(float $x1, float $y1, float $x2, float $y2, array $rgb = [0,0,0]): void
    {
        $this->content .= sprintf("q %.3F %.3F %.3F RG 0.8 w %.2F %.2F m %.2F %.2F l S Q\n", $rgb[0], $rgb[1], $rgb[2], $x1, $y1, $x2, $y2);
    }

    public function title(string $title, string $subtitle = ''): void
    {
        $this->text(42, $this->y, $title, 28, true, [0.04, 0.04, 0.04]);
        $this->y -= 22;
        if ($subtitle !== '') {
            $this->text(43, $this->y, $subtitle, 10, false, [0.38, 0.38, 0.38]);
            $this->y -= 28;
        }
    }

    public function section(string $title): void
    {
        $this->ensure(54);
        $this->y -= 18;
        $this->text(42, $this->y, $title, 15, true, [0.05, 0.05, 0.05]);
        $this->line(42, $this->y - 8, 553, $this->y - 8, [0.87, 0.87, 0.87]);
        $this->y -= 26;
    }

    public function summaryCards(array $cards): void
    {
        $this->ensure(94);
        $x = 42;
        $w = 119;
        foreach ($cards as $card) {
            $this->rect($x, $this->y - 64, $w, 64, [0.965, 0.955, 0.94]);
            $this->text($x + 12, $this->y - 24, (string)$card[0], 18, true, [0.04, 0.04, 0.04]);
            $this->text($x + 12, $this->y - 45, strtoupper((string)$card[1]), 7, true, [0.38, 0.38, 0.38]);
            $x += $w + 12;
        }
        $this->y -= 82;
    }

    private function wrap(string $text, int $max): array
    {
        $text = $this->clean($text);
        if (strlen($text) <= $max) {
            return [$text];
        }
        $words = explode(' ', $text);
        $lines = [''];
        foreach ($words as $word) {
            $i = count($lines) - 1;
            $candidate = trim($lines[$i] . ' ' . $word);
            if (strlen($candidate) > $max && $lines[$i] !== '') {
                $lines[] = $word;
            } else {
                $lines[$i] = $candidate;
            }
        }
        return array_slice($lines, 0, 2);
    }

    public function table(array $headers, array $rows, array $widths): void
    {
        $this->ensure(56);
        $x = 42;
        $headerY = $this->y;
        $this->rect($x, $headerY - 25, array_sum($widths), 25, [0.05, 0.05, 0.05]);
        foreach ($headers as $i => $header) {
            $this->text($x + 7, $headerY - 16, strtoupper((string)$header), 7, true, [1,1,1]);
            $x += $widths[$i];
        }
        $this->y -= 25;

        if (!$rows) {
            $this->rect(42, $this->y - 32, array_sum($widths), 32, [0.99, 0.99, 0.99]);
            $this->text(52, $this->y - 20, 'No records available for this report section.', 9, false, [0.38,0.38,0.38]);
            $this->y -= 38;
            return;
        }

        foreach ($rows as $row) {
            $wrapped = [];
            $lineCount = 1;
            foreach ($row as $i => $cell) {
                $maxChars = max(10, (int)floor($widths[$i] / 5));
                $lines = $this->wrap((string)$cell, $maxChars);
                $wrapped[$i] = $lines;
                $lineCount = max($lineCount, count($lines));
            }
            $rowH = 24 + (($lineCount - 1) * 10);
            $this->ensure($rowH + 10);
            $this->rect(42, $this->y - $rowH, array_sum($widths), $rowH, [1,1,1]);
            $this->line(42, $this->y - $rowH, 42 + array_sum($widths), $this->y - $rowH, [0.9,0.9,0.9]);
            $x = 42;
            foreach ($wrapped as $i => $lines) {
                foreach ($lines as $j => $line) {
                    $this->text($x + 7, $this->y - 16 - ($j * 10), $line, 8, false, [0.11,0.11,0.11]);
                }
                $x += $widths[$i];
            }
            $this->y -= $rowH;
        }
        $this->y -= 12;
    }

    public function output(string $filename): void
    {
        if ($this->content !== '') {
            $this->footer();
            $this->pages[] = $this->content;
            $this->content = '';
        }

        $objects = [];
        $objects[] = '<< /Type /Catalog /Pages 2 0 R >>';
        $objects[] = 'PAGES_PLACEHOLDER';
        $objects[] = '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>';
        $objects[] = '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>';

        $kids = [];
        foreach ($this->pages as $content) {
            $pageId = count($objects) + 1;
            $contentId = $pageId + 1;
            $kids[] = $pageId . ' 0 R';
            $stream = "<< /Length " . strlen($content) . " >>\nstream\n" . $content . "endstream";
            $objects[] = "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 " . self::W . " " . self::H . "] /Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents {$contentId} 0 R >>";
            $objects[] = $stream;
        }
        $objects[1] = '<< /Type /Pages /Kids [' . implode(' ', $kids) . '] /Count ' . count($this->pages) . ' >>';

        $pdf = "%PDF-1.4\n%\xE2\xE3\xCF\xD3\n";
        $offsets = [0];
        foreach ($objects as $i => $object) {
            $offsets[] = strlen($pdf);
            $pdf .= ($i + 1) . " 0 obj\n" . $object . "\nendobj\n";
        }
        $xref = strlen($pdf);
        $pdf .= "xref\n0 " . (count($objects) + 1) . "\n0000000000 65535 f \n";
        for ($i = 1; $i <= count($objects); $i++) {
            $pdf .= sprintf("%010d 00000 n \n", $offsets[$i]);
        }
        $pdf .= "trailer\n<< /Size " . (count($objects) + 1) . " /Root 1 0 R >>\nstartxref\n" . $xref . "\n%%EOF";

        header('Content-Type: application/pdf');
        header('Content-Disposition: attachment; filename="' . $filename . '"');
        header('Content-Length: ' . strlen($pdf));
        echo $pdf;
        exit;
    }
}

function pdf_money(float $amount): string
{
    return CURRENCY . ' ' . number_format($amount, 2);
}

$pdf = new PremiumPdf();
$pdf->title('Arts Gallery Report', 'Inventory, sales, customer, and order performance summary generated for admin review.');
$pdf->summaryCards([
    [$summary['artworks'], 'Artworks'],
    [$summary['orders'], 'Orders'],
    [$summary['customers'], 'Customers'],
    [pdf_money($summary['revenue']), 'Total Revenue'],
]);

$pdf->section('Order Status Summary');
$pdf->table(['Status', 'Orders', 'Value'], array_map(fn($row) => [
    $row['status'],
    (int)$row['total'],
    pdf_money((float)$row['value']),
], $orderStatuses), [210, 110, 190]);

$pdf->section('Inventory Report');
$pdf->table(['Category', 'Status', 'Total Artworks', 'Inventory Value'], array_map(fn($row) => [
    $row['category'],
    $row['status'],
    (int)$row['total'],
    pdf_money((float)$row['value']),
], $inventory), [145, 120, 115, 130]);

$pdf->section('Sales Report - Last 30 Days');
$pdf->table(['Date', 'Orders', 'Total Value'], array_map(fn($row) => [
    $row['order_date'],
    (int)$row['orders_count'],
    pdf_money((float)$row['total_value']),
], $sales), [180, 120, 210]);

$pdf->section('Top Customers');
$pdf->table(['Name', 'Email', 'Orders', 'Total'], array_map(fn($row) => [
    $row['name'],
    $row['email'],
    (int)$row['orders_count'],
    pdf_money((float)$row['total_value']),
], $topCustomers), [145, 190, 70, 105]);

$pdf->output('arts-gallery-report-' . date('Ymd-His') . '.pdf');
